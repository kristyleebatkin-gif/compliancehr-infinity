export function tenantGroupOf(entityName) {
  if (PLATFORM_ENTITIES.includes(entityName)) return 'platform';
  if (SHARED_LIBRARY_ENTITIES.includes(entityName)) return 'shared_library';
  if (SHARED_WITH_COPIES_ENTITIES.includes(entityName)) return 'shared_with_copies';
  if (BUSINESS_OWNED_ENTITIES.includes(entityName)) return 'business';
  return 'unclassified';
}
