export function computeOrganisationHealthIndex(dimensions = DEFAULT_ORG_HEALTH_DIMENSIONS) {
  const totalWeight = dimensions.reduce((sum, d) => sum + Number(d.weight || 0), 0) || 1;
  const weightedSum = dimensions.reduce((sum, d) => sum + Number(d.score || 0) * Number(d.weight || 0), 0);
  return Number((weightedSum / totalWeight).toFixed(1));
}

