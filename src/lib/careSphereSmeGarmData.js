// Formula: Risk Score = Impact × Likelihood
// 20-25 Extreme | 15-19 High | 8-14 Medium | 1-7 Low
export function computeRiskScore(impact, likelihood) {
  return Number(impact || 1) * Number(likelihood || 1);
}

export function getRiskRatingBand(score) {
  const s = Number(score || 0);
  if (s >= 20) return { rating: 'Extreme', color: '#EF4444', range: '20–25' };
  if (s >= 15) return { rating: 'High', color: '#F97316', range: '15–19' };
  if (s >= 8) return { rating: 'Medium', color: '#FBBF24', range: '8–14' };
  return { rating: 'Low', color: '#22C55E', range: '1–7' };
}

// Formula: Benefit Achievement % = (Current − Baseline) ÷ (Target − Baseline)
export function computeBenefitAchievement(current, baseline, target) {
  const denom = Number(target) - Number(baseline);
  if (denom === 0) return 100;
  const pct = ((Number(current) - Number(baseline)) / denom) * 100;
  return Number(Math.max(0, Math.min(150, pct)).toFixed(1));
}

// Formula: LQI = 20% Completeness + 20% Accuracy + 15% Currency + 15% Traceability + 10% Ownership + 10% Evidence + 10% Assurance
export const DEFAULT_LQI_METRICS = {
  completeness: 95,
  accuracy: 94,
  currency: 92,
  traceability: 93,
  ownership: 96,
  evidence: 92,
  assurance: 91,
};

export function computeLineageQualityIndex(m = DEFAULT_LQI_METRICS) {
  const lqi =
    0.20 * Number(m.completeness || 0) +
    0.20 * Number(m.accuracy || 0) +
    0.15 * Number(m.currency || 0) +
    0.15 * Number(m.traceability || 0) +
    0.10 * Number(m.ownership || 0) +
    0.10 * Number(m.evidence || 0) +
    0.10 * Number(m.assurance || 0);
  return Number(lqi.toFixed(1));
}

