// Build all 356 Individual Checkpoint Records (CHK-001 to CHK-356)
export function buildAll356Checkpoints(liveCounts = {}) {
  const list = [];
  let seq = 1;
  for (const cat of MASTER_17_AUDIT_CATEGORIES) {
    const [dStart, dEnd] = cat.docRange;
    const evidenceCount = Number(liveCounts[cat.evidenceKey] || 0);
    for (let i = 0; i < cat.checkpointCount; i++) {
      const code = `CHK-${String(seq).padStart(3, '0')}`;
      const topic = cat.topics[i] || `${cat.title} Control #${i + 1}`;
      const docNum = dStart + (i % (dEnd - dStart + 1));
      const docCode = `DOC-${String(docNum).padStart(3, '0')}`;
      // Rule: Never mark a checkpoint compliant based solely on a template!
      // Require live operational evidence records in the linked entity.
      const hasOperationalEvidence = evidenceCount > 0;
      const defaultStatus = hasOperationalEvidence
        ? 'Operationally Evidenced'
        : 'Template Only — Operational Evidence Required';

      list.push({
        id: code,
        seq,
        categoryId: cat.id,
        categoryCode: cat.code,
        categoryTitle: cat.title,
        subject: topic,
        legislation: cat.legislation,
        applicability: 'Mandatory — NDIS & HR Operations',
        requiredDocCode: docCode,
        evidenceEntity: cat.evidenceKey,
        evidenceCount,
        hasOperationalEvidence,
        assessmentResult: defaultStatus,
        gapIdentified: hasOperationalEvidence
          ? 'None — active operational records linked'
          : `Requires live ${cat.evidenceKey} records to substantiate template ${docCode}`,
        correctiveAction: hasOperationalEvidence
          ? 'Maintain scheduled 90-day verification cycle'
          : `Capture and verify live ${cat.evidenceKey} evidence for ${topic}`,
        dueDate: '2026-11-30',
        owner: 'Compliance Administrator',
        route: cat.route,
      });
      seq++;
    }
  }
  return list;
}

