import { jsPDF } from 'jspdf';
import { drawCompanyBranding, drawDocumentFooter } from '@/lib/companyBranding';
import { itemStatus } from '@/lib/documentationChecklists';

export const today = () => new Date().toISOString().slice(0, 10);
const STATUS_STYLE = {
  Current: { rgb: [22, 128, 61], fill: [226, 244, 232] },
  Overdue: { rgb: [180, 40, 30], fill: [253, 226, 224] },
  'Not logged': { rgb: [100, 116, 139], fill: [241, 245, 249] },
};

function docHeader(doc, title, subtitle, generatedBy) {
  const pageW = doc.internal.pageSize.getWidth();
  let y = 64;
  drawCompanyBranding(doc, 40, y, { fontSize: 18 });
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(120);
  doc.text('DOCUMENTATION & COMPLIANCE', pageW - 40, y, { align: 'right' });
  y += 42;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(30);
  doc.text(title, 40, y, { maxWidth: pageW - 180 });
  y += 16;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(110);
  doc.text([subtitle, new Date().toLocaleString('en-AU'), generatedBy && `Prepared by ${generatedBy}`].filter(Boolean).join('  |  '), 40, y);
  return y + 24;
}

function ensureSpace(doc, y, needed, pageH) {
  if (y > pageH - needed) { doc.addPage(); return 64; }
  return y;
}

function signOff(doc, y, pageH) {
  y = ensureSpace(doc, y, 140, pageH);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(30);
  doc.text('Reviewed by: ______________________    Signature: ______________________', 40, y + 7);
  doc.text('Date: ______________________    Next review due: ______________________', 40, y + 27);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(120);
  doc.text('Generated by ComplianceHR Infinity from the live Documentation & Compliance Checklist.', 40, y + 47);
  return y + 60;
}

// Complete audit checklist: every section and item with cadence, status,
// last logged evidence and next due date.
export function buildDocumentationChecklistPdf({ profile, kind, sections, latestByKey, generatedBy = '' }) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const kindLabel = kind === 'participant' ? 'Participant' : 'Employee';
  let y = docHeader(doc, `Documentation & Compliance Audit Checklist: ${profile.full_name}`, `${kindLabel} profile audit checklist`, generatedBy);

  for (const section of sections) {
    y = ensureSpace(doc, y, 120, pageH);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(30);
    doc.text(section.title, 40, y);
    doc.setDrawColor(215);
    doc.line(40, y + 6, pageW - 40, y + 6);
    y += 22;
    for (const item of section.items) {
      y = ensureSpace(doc, y, 70, pageH);
      const status = itemStatus(latestByKey.get(item.key));
      const style = STATUS_STYLE[status.label] || STATUS_STYLE['Not logged'];
      doc.setDrawColor(120);
      doc.rect(40, y - 9, 10, 10);
      doc.setFillColor(...style.fill);
      doc.roundedRect(56, y - 10, 70, 16, 4, 4, 'F');
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.setTextColor(...style.rgb);
      doc.text(status.label.toUpperCase(), 61, y + 2);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9.5);
      doc.setTextColor(50);
      const lines = doc.splitTextToSize(item.title, pageW - 200);
      doc.text(lines, 132, y);
      y += lines.length * 12;
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8.5);
      doc.setTextColor(120);
      const meta = latestByKey.get(item.key);
      const metaLines = doc.splitTextToSize(
        `Cadence: ${item.cadence}${meta ? ` · last logged ${meta.completed_date} by ${meta.completed_by}${meta.next_due_date ? ` · next due ${meta.next_due_date}` : ''}` : ' · not yet logged'}`,
        pageW - 90,
      );
      for (const line of metaLines) {
        y = ensureSpace(doc, y, 40, pageH);
        doc.text(line, 48, y);
        y += 11;
      }
      y += 6;
    }
    y += 6;
  }
  signOff(doc, y + 4, pageH);
  drawDocumentFooter(doc, { title: `Documentation & Compliance Audit Checklist: ${profile.full_name}`, code: 'DOC-AUD-CHK' });
  return doc;
}

// PDF audit report generated from the checklist: summary, section results
// and the corrective action register for anything overdue or not yet logged.
export function buildDocumentationAuditReportPdf({ profile, kind, sections, latestByKey, generatedBy = '' }) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const kindLabel = kind === 'participant' ? 'Participant' : 'Employee';
  let y = docHeader(doc, `Documentation & Compliance Audit Report: ${profile.full_name}`, `${kindLabel} profile audit report`, generatedBy);

  const allItems = sections.flatMap((s) => s.items);
  const overdue = allItems.filter((item) => itemStatus(latestByKey.get(item.key)).label === 'Overdue');
  const notLogged = allItems.filter((item) => itemStatus(latestByKey.get(item.key)).label === 'Not logged');
  const current = allItems.length - overdue.length - notLogged.length;

  doc.setFillColor(226, 240, 252);
  doc.roundedRect(40, y, pageW - 80, 40, 5, 5, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(23, 78, 138);
  doc.text(`Result: ${current}/${allItems.length} items current  |  ${overdue.length} overdue  |  ${notLogged.length} not yet logged`, 54, y + 24);
  y += 58;

  const heading = (text) => {
    y = ensureSpace(doc, y, 110, pageH);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(30);
    doc.text(text, 40, y);
    doc.setDrawColor(215);
    doc.line(40, y + 6, pageW - 40, y + 6);
    y += 22;
  };

  heading('Section Results');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(60);
  doc.text('SECTION', 40, y);
  doc.text('RESULT', pageW - 80, y, { align: 'right' });
  y += 12;
  doc.setDrawColor(210);
  doc.line(40, y, pageW - 40, y);
  y += 13;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  for (const section of sections) {
    y = ensureSpace(doc, y, 40, pageH);
    const sectionCurrent = section.items.filter((item) => itemStatus(latestByKey.get(item.key)).label === 'Current').length;
    doc.setTextColor(50);
    doc.text(section.title, 40, y, { maxWidth: pageW - 170 });
    doc.setTextColor(23, 78, 138);
    doc.text(`${sectionCurrent}/${section.items.length} current`, pageW - 80, y, { align: 'right' });
    y += 16;
  }
  y += 6;

  heading(`Corrective & Follow-up Register (${overdue.length + notLogged.length} open)`);
  if (overdue.length + notLogged.length === 0) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.setTextColor(70);
    doc.text('No corrective actions required: every checklist item was logged and in date at audit time.', 40, y);
    y += 20;
  } else {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(60);
    doc.text('ACTION', 40, y);
    doc.text('CADENCE', pageW * 0.56, y);
    doc.text('DUE', pageW * 0.76, y, { align: 'right' });
    doc.text('STATUS', pageW - 40, y, { align: 'right' });
    y += 12;
    doc.setDrawColor(210);
    doc.line(40, y, pageW - 40, y);
    y += 13;
    doc.setFont('helvetica', 'normal');
    for (const item of [...overdue, ...notLogged]) {
      y = ensureSpace(doc, y, 40, pageH);
      const meta = latestByKey.get(item.key);
      doc.setFontSize(9);
      doc.setTextColor(50);
      doc.text(doc.splitTextToSize(item.title, pageW * 0.5)[0], 40, y);
      doc.text(item.cadence, pageW * 0.56, y);
      doc.text(meta?.next_due_date || 'log now', pageW * 0.76, y, { align: 'right' });
      doc.setTextColor(180, 60, 40);
      doc.text(meta ? 'Overdue' : 'Not logged', pageW - 40, y, { align: 'right' });
      doc.setTextColor(50);
      y += 16;
    }
  }

  signOff(doc, y + 4, pageH);
  drawDocumentFooter(doc, { title: `Documentation & Compliance Audit Report: ${profile.full_name}`, code: 'DOC-AUD-RPT' });
  return doc;
}