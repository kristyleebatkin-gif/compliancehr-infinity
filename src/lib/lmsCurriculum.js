function buildQuiz(number) {
  const count = 5;
  const start = (number - 1) % SHARED_QUIZ.length;
  const picked = [];
  for (let i = 0; i < count; i++) picked.push(SHARED_QUIZ[(start + i) % SHARED_QUIZ.length]);
  return picked;
}

export function getModuleFull(m) {
  const lower = m.title.charAt(0).toLowerCase() + m.title.slice(1);
  const scenario = getScenario(m.number);
  return {
    ...m,
    guide: `${m.title}. ${m.description} This module develops the knowledge and skills to apply these principles in daily practice, ensuring safeguarding, dignity, and quality outcomes for participants. Work through the learner guide, lesson content and workplace scenarios, then complete the knowledge quiz, practical assessment and supervisor competency checklist to receive your certificate of completion.`,
    scenarios: scenario
      ? [scenario.scenario]
      : [
          `A participant you support is in a situation where ${lower} applies. Describe how you would respond, what actions you would take, and how you would keep the participant at the centre of decisions.`,
          `During a shift, a colleague is unsure how to apply ${lower}. Explain how you would support them to follow correct practice and what resources you would use.`,
        ],
    practicalScenario: scenario
      ? {
          scenario: scenario.scenario,
          learnerTask: scenario.learnerTask,
          expectedResponse: scenario.expectedResponse,
          evidenceRequired: scenario.evidenceRequired,
        }
      : null,
    practical: [
      `Demonstrate application of ${lower} in a simulated or real workplace task.`,
      `Complete the practical observation checklist with your supervisor.`,
      `Submit evidence of applying these principles in a real or simulated support setting.`,
    ],
    supervisorChecklist: scenario ? scenario.supervisorChecklist : null,
    supervisor: [
      `Worker can explain the key principles of ${lower}.`,
      `Worker consistently applies these principles during shifts.`,
      `Worker documents and reports in line with organisational policy and procedure.`,
    ],
    components: LMS_COMPONENTS,
    quiz: getModuleQuiz(m.number) || buildQuiz(m.number),
  };
}

